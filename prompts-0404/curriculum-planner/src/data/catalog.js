/** Helper: get a semester label like "Fall Year 1" */
export function semesterLabel(index) {
  const year = Math.floor(index / 2) + 1;
  const term = index % 2 === 0 ? "Fall" : "Spring";
  return `${term} – Year ${year}`;
}

/** Helper: get course by id */
export function getCourse(id) {
  return courses.find((c) => c.id === id);
}

/** Helper: get all visible courses */
export function getVisibleCourses() {
  return courses.filter((c) => !c.hidden);
}
